import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { OFFICIAL, clone, status } = require('../data/hours.js');
const instant = value => Date.parse(`${value}-03:00`);
const check = (date, label, hint, hours = OFFICIAL) => {
  const result = status(hours, instant(date));
  assert.equal(result.label, label, `${date}: ${JSON.stringify(result)}`);
  if (hint) assert.match(result.hint, hint, date);
};

check('2026-11-23T12:00', 'FECHADO AGORA', /Hoje estamos fechados.*terça-feira às 16h00/);
check('2026-11-24T15:29', 'FECHADO AGORA', /Abrimos hoje às 16h00/);
check('2026-11-24T15:30', 'ABRIMOS EM BREVE', /Faltam 30 minutos/);
check('2026-11-24T15:45', 'ABRIMOS EM BREVE', /Faltam 15 minutos/);
check('2026-11-24T16:00', 'ABERTO AGORA', /22h00/);
check('2026-11-24T21:30', 'ENCERRANDO EM BREVE', /Faltam 30 minutos/);
check('2026-11-24T22:00', 'FECHADO AGORA', /amanhã às 16h00/);
check('2026-11-25T16:00', 'ABERTO AGORA', /22h00/);
check('2026-11-26T22:30', 'ENCERRANDO EM BREVE', /Faltam 30 minutos/);
check('2026-11-26T23:00', 'FECHADO AGORA', /amanhã às 15h00/);
check('2026-11-27T15:00', 'ABERTO AGORA', /meia-noite/);
check('2026-11-27T23:30', 'ENCERRANDO EM BREVE', /Faltam 30 minutos/);
check('2026-11-27T23:59', 'ENCERRANDO EM BREVE', /Falta 1 minuto/);
check('2026-11-28T00:00', 'FECHADO AGORA', /hoje às 12h00/);
check('2026-11-28T12:00', 'ABERTO AGORA', /meia-noite/);
check('2026-11-28T23:59', 'ENCERRANDO EM BREVE', /Falta 1 minuto/);
check('2026-11-29T00:00', 'FECHADO AGORA', /hoje às 12h00/);
check('2026-11-29T12:00', 'ABERTO AGORA', /22h00/);
check('2026-11-29T22:00', 'FECHADO AGORA', /terça-feira às 16h00/);

const holiday = clone(OFFICIAL);
holiday.specials.push({ date: '2026-11-24', label: 'Feriado', open: false, intervals: [] });
check('2026-11-24T16:00', 'FECHADO AGORA', /Hoje estamos fechados.*quarta-feira às 16h00/, holiday);
const extension = clone(OFFICIAL);
extension.specials.push({ date: '2026-11-26', label: 'Evento', open: true, intervals: [{ start: '16:00', end: '23:30' }] });
check('2026-11-26T23:00', 'ENCERRANDO EM BREVE', /Faltam 30 minutos/, extension);
const earlyClose = clone(OFFICIAL);
earlyClose.specials.push({ date: '2026-11-26', label: 'Encerramento antecipado', open: true, intervals: [{ start: '16:00', end: '20:00' }] });
check('2026-11-26T20:00', 'FECHADO AGORA', /amanhã às 15h00/, earlyClose);
const manualOpen = clone(OFFICIAL);
manualOpen.manual = 'open'; manualOpen.manualUntil = new Date(instant('2026-11-23T18:00')).toISOString();
check('2026-11-23T17:45', 'ENCERRANDO EM BREVE', /Faltam 15 minutos/, manualOpen);
check('2026-11-23T18:00', 'FECHADO AGORA', /terça-feira às 16h00/, manualOpen);
const manualClosed = clone(OFFICIAL);
manualClosed.manual = 'closed'; manualClosed.manualUntil = new Date(instant('2026-11-24T17:00')).toISOString();
check('2026-11-24T16:45', 'ABRIMOS EM BREVE', /Faltam 15 minutos/, manualClosed);
check('2026-11-24T17:00', 'ABERTO AGORA', /22h00/, manualClosed);
const manualOpenIntoRegular = clone(OFFICIAL);
manualOpenIntoRegular.manual = 'open'; manualOpenIntoRegular.manualUntil = new Date(instant('2026-11-24T18:00')).toISOString();
check('2026-11-24T17:45', 'ABERTO AGORA', /22h00/, manualOpenIntoRegular);
const manualOpenNoLimit = clone(OFFICIAL);
manualOpenNoLimit.manual = 'open';
check('2026-11-23T12:00', 'ABERTO AGORA', /ajuste manual/, manualOpenNoLimit);
assert.equal(status(OFFICIAL, NaN).tone, 'unavailable');
